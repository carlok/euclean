"""A library of declarations: the one input format everything here reads.

A library is a JSON Lines file. The first line is a header; every other line is
one declaration, listed after everything it cites.

Header::

    {"format": "interestkit-library/1",
     "definitions": {"Obj": {"statement": "Type", "uses": []},
                     "R0":  {"statement": "Obj → Obj → Obj → Prop", "uses": ["Obj"]}},
     "costs": ["loc", "term"],
     "meta": {...}}

Declaration::

    {"name": "t0_00012",
     "statement": "∀ (v0 : Obj) ..., ...",
     "axiom": false,
     "uses": ["Obj", "R0"],             # definitions needed to state it, directly
     "premises": {"t0_00003": 2, "a4": 1},   # what its proof cites, with multiplicity
     "cost": {"loc": 3, "term": 7},     # cost of this one proof step, premises given
     "label": "N",                      # optional ground truth
     ...}                               # any other fields are carried along

Axioms have no proof: no premises, no cost. They are never expanded, so
V(T | empty) means "from the axioms".

Nothing here knows where a library came from. A Mathlib slice, a Lean project,
or a corpus generated by a theorem prover all fit, provided someone can say what
each proof cites and what each step costs.
"""

import json

FORMAT = "interestkit-library/1"


class Library:
    def __init__(self, definitions, decls, costs=(), meta=None):
        self.definitions = definitions
        self.decls = decls
        self.by_name = {d["name"]: d for d in decls}
        self.costs = tuple(costs)
        self.meta = meta or {}
        self._check()

    # -- construction ------------------------------------------------------

    @classmethod
    def load(cls, path):
        with open(path, encoding="utf-8") as fh:
            rows = [json.loads(x) for x in fh if x.strip()]
        head, decls = rows[0], rows[1:]
        if head.get("format") != FORMAT:
            raise ValueError(f"{path}: not an {FORMAT} file")
        return cls(head["definitions"], decls, head.get("costs", ()), head.get("meta"))

    def save(self, path):
        head = {"format": FORMAT, "definitions": self.definitions,
                "costs": list(self.costs), "meta": self.meta}
        with open(path, "w", encoding="utf-8") as fh:
            for row in [head] + self.decls:
                fh.write(json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n")

    def _check(self):
        seen = set()
        for d in self.decls:
            n = d["name"]
            if n in seen:
                raise ValueError(f"duplicate declaration {n!r}")
            for p in d.get("premises", {}):
                if p not in seen:
                    raise ValueError(f"{n!r} cites {p!r}, which is not listed before it")
            for u in d.get("uses", ()):
                if u not in self.definitions:
                    raise ValueError(f"{n!r} uses undefined {u!r}")
            if d.get("axiom") and d.get("premises"):
                raise ValueError(f"axiom {n!r} cites premises")
            seen.add(n)

    # -- views -------------------------------------------------------------

    def theorems(self):
        return [d for d in self.decls if not d.get("axiom")]

    def axioms(self):
        return [d["name"] for d in self.decls if d.get("axiom")]

    def direct_users(self):
        """name -> number of declarations whose proof cites it directly: |D(T)|."""
        out = {d["name"]: 0 for d in self.decls}
        for d in self.decls:
            for p in d.get("premises", {}):
                out[p] += 1
        return out

    def vocabulary(self, names):
        """C(X) for a set of definitions: the closure under `uses`."""
        out, stack = set(), list(names)
        while stack:
            u = stack.pop()
            if u not in out:
                out.add(u)
                stack.extend(self.definitions[u].get("uses", ()))
        return out

    def vocabulary_of(self, decl):
        return self.vocabulary(self.by_name[decl]["uses"] if isinstance(decl, str) else decl["uses"])
